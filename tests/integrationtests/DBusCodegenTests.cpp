// Tests of the code generated by sdbus-c++-xml2cpp during the build from
// tests/compiletests/dbus-api/org.sdbuscpp.codegentests.xml

#include "TestFixture.h"
#include "Defs.h"
#include "codegentests-adaptor.h"
#include "codegentests-proxy.h"
#include <sdbus-c++/sdbus-c++.h>

#include <atomic>
#include <cstdint>
#include <gtest/gtest.h>
#include <gmock/gmock.h>
#include <memory>
#include <mutex>
#include <optional>
#include <string>

using ::testing::Eq;
using ::testing::Optional;
using namespace sdbus::test;

namespace {

const sdbus::ObjectPath CODEGEN_OBJECT_PATH{"/org/sdbuscpp/integrationtests/codegen"};
const sdbus::InterfaceName CODEGEN_INTERFACE_NAME{org::sdbuscpp::codegentests_proxy::INTERFACE_NAME};
const sdbus::InterfaceName PROPERTY_CHANGES_INTERFACE_NAME{org::sdbuscpp::codegentests::PropertyChanges_proxy::INTERFACE_NAME};
const sdbus::PropertyName CHANGING_PROPERTY{"changing"};
const sdbus::PropertyName INVALIDATING_PROPERTY{"invalidating"};
const sdbus::PropertyName VARIANT_PROPERTY{"variant"};

// The org.sdbuscpp.codegentests interface of the XML cannot be registered on the bus, since its
// argument names are deliberately not valid D-Bus member names. Its `changing` property is
// registered by hand instead, so that the object has the property on two interfaces.
class CodegenAdaptor final : public sdbus::AdaptorInterfaces<org::sdbuscpp::codegentests::PropertyChanges_adaptor>
{
public:
    CodegenAdaptor(sdbus::IConnection& connection, sdbus::ObjectPath path)
        : AdaptorInterfaces(connection, std::move(path))
    {
        registerAdaptor();
        getObject().addVTable(sdbus::registerProperty(CHANGING_PROPERTY).withGetter([this](){ return changingValue; }))
                   .forInterface(CODEGEN_INTERFACE_NAME);
    }

    CodegenAdaptor(const CodegenAdaptor&) = delete;
    CodegenAdaptor& operator=(const CodegenAdaptor&) = delete;
    CodegenAdaptor(CodegenAdaptor&&) = delete;
    CodegenAdaptor& operator=(CodegenAdaptor&&) = delete;

    ~CodegenAdaptor()
    {
        unregisterAdaptor();
    }

    uint32_t changingValue{UINT32_VALUE};
    sdbus::Variant variantValue{STRING_VALUE};

private:
    uint32_t changing() override { return changingValue; }
    std::string invalidating() override { return STRING_VALUE; }
    void invalidating(const std::string& /*value*/) override {}
    std::string inheriting() override { return {}; }
    void inheriting(const std::string& /*value*/) override {}
    sdbus::Variant variant() override { return variantValue; }
    int32_t constant() override { return INT32_VALUE; }
    void writeOnly(const uint32_t& /*value*/) override {}
};

// Only PropertyChanges_proxy, so that a change on the other interface of the object reaches its
// PropertiesChanged subscription and must be filtered out by the interface name
class CodegenProxy final : public sdbus::ProxyInterfaces<org::sdbuscpp::codegentests::PropertyChanges_proxy>
{
public:
    CodegenProxy(sdbus::IConnection& connection, sdbus::ServiceName destination, sdbus::ObjectPath path)
        : ProxyInterfaces(connection, std::move(destination), std::move(path))
    {
        registerProxy();
    }

    CodegenProxy(const CodegenProxy&) = delete;
    CodegenProxy& operator=(const CodegenProxy&) = delete;
    CodegenProxy(CodegenProxy&&) = delete;
    CodegenProxy& operator=(CodegenProxy&&) = delete;

    ~CodegenProxy()
    {
        unregisterProxy();
    }

    // Handlers run in the proxy connection event loop thread
    std::atomic<int> changingNotifications{0};
    std::atomic<bool> invalidatingNotified{false};
    std::atomic<bool> variantNotified{false};
    std::mutex mutex;
    std::optional<uint32_t> changingValue;
    std::optional<std::string> invalidatingValue{STRING_VALUE};
    std::optional<sdbus::Variant> variantValue;

private:
    void onChangingPropertyChanged(const std::optional<uint32_t>& value) override
    {
        std::lock_guard lock{mutex};
        changingValue = value;
        ++changingNotifications;
    }

    void onInvalidatingPropertyChanged(const std::optional<std::string>& value) override
    {
        std::lock_guard lock{mutex};
        invalidatingValue = value;
        invalidatingNotified = true;
    }

    void onVariantPropertyChanged(const std::optional<sdbus::Variant>& value) override
    {
        std::lock_guard lock{mutex};
        variantValue = value;
        variantNotified = true;
    }
};

template <typename EventLoop>
class GeneratedProxy : public TestFixture<EventLoop>
{
protected:
    void SetUp() override
    {
        adaptor_ = std::make_unique<CodegenAdaptor>(*this->s_adaptorConnection, CODEGEN_OBJECT_PATH);
        proxy_ = std::make_unique<CodegenProxy>(*this->s_proxyConnection, SERVICE_NAME, CODEGEN_OBJECT_PATH);
    }

    void TearDown() override
    {
        proxy_.reset();
        adaptor_.reset();
    }

    std::unique_ptr<CodegenAdaptor> adaptor_;
    std::unique_ptr<CodegenProxy> proxy_;
};

TYPED_TEST_SUITE(GeneratedProxy, EventLoopTags);

} // namespace

TYPED_TEST(GeneratedProxy, PassesChangedPropertyValueToGeneratedHandler)
{
    this->adaptor_->changingValue = UINT32_VALUE + 1;

    this->adaptor_->getObject().emitPropertiesChangedSignal(PROPERTY_CHANGES_INTERFACE_NAME, {CHANGING_PROPERTY});

    ASSERT_TRUE(waitUntil([&]{ return this->proxy_->changingNotifications > 0; })) << "Handler of the changed `changing` property was not called";
    std::lock_guard lock{this->proxy_->mutex};
    EXPECT_THAT(this->proxy_->changingValue, Optional(Eq(UINT32_VALUE + 1))) << "Changed property shall be passed with its new value";
}

TYPED_TEST(GeneratedProxy, PassesEmptyValueOfInvalidatedPropertyToGeneratedHandler)
{
    // The `invalidating` property is annotated with EmitsChangedSignal=invalidates
    this->adaptor_->getObject().emitPropertiesChangedSignal(PROPERTY_CHANGES_INTERFACE_NAME, {INVALIDATING_PROPERTY});

    ASSERT_TRUE(waitUntil(this->proxy_->invalidatingNotified)) << "Handler of the invalidated `invalidating` property was not called";
    std::lock_guard lock{this->proxy_->mutex};
    EXPECT_FALSE(this->proxy_->invalidatingValue.has_value())
        << "Invalidated property shall be passed without value, but got " << this->proxy_->invalidatingValue.value_or("");
}

TYPED_TEST(GeneratedProxy, PassesVariantPropertyValueToGeneratedHandlerUnwrappedFromChangedPropertiesMap)
{
    this->adaptor_->variantValue = sdbus::Variant{INT32_VALUE};

    this->adaptor_->getObject().emitPropertiesChangedSignal(PROPERTY_CHANGES_INTERFACE_NAME, {VARIANT_PROPERTY});

    ASSERT_TRUE(waitUntil(this->proxy_->variantNotified)) << "Handler of the changed `variant` property was not called";
    std::lock_guard lock{this->proxy_->mutex};
    ASSERT_TRUE(this->proxy_->variantValue.has_value()) << "Changed property of type `v` shall be passed with its value";
    ASSERT_TRUE(this->proxy_->variantValue->template containsValueOfType<int32_t>())
        << "Value of a property of type `v` shall be the property's variant, not the variant of the changed properties map wrapping it, but it holds type "
        << this->proxy_->variantValue->peekValueType();
    EXPECT_THAT(this->proxy_->variantValue->template get<int32_t>(), Eq(INT32_VALUE));
}

TYPED_TEST(GeneratedProxy, DispatchesPropertiesChangedTogetherToTheirHandlers)
{
    this->adaptor_->getObject().emitPropertiesChangedSignal(PROPERTY_CHANGES_INTERFACE_NAME, {CHANGING_PROPERTY, INVALIDATING_PROPERTY, VARIANT_PROPERTY});

    ASSERT_TRUE(waitUntil([&]{ return this->proxy_->changingNotifications > 0
                                   && this->proxy_->invalidatingNotified
                                   && this->proxy_->variantNotified; }))
        << "Each property of one PropertiesChanged signal shall be passed to its own handler: changing="
        << this->proxy_->changingNotifications.load() << ", invalidating=" << this->proxy_->invalidatingNotified.load()
        << ", variant=" << this->proxy_->variantNotified.load();
}

TYPED_TEST(GeneratedProxy, DoesNotPassPropertyChangeOnOtherInterfaceToGeneratedHandler)
{
    // Both interfaces of the object have the `changing` property
    this->adaptor_->getObject().emitPropertiesChangedSignal(CODEGEN_INTERFACE_NAME, {CHANGING_PROPERTY});
    // Signals are delivered in order, so the notification about `invalidating` comes after the one about `changing`
    this->adaptor_->getObject().emitPropertiesChangedSignal(PROPERTY_CHANGES_INTERFACE_NAME, {INVALIDATING_PROPERTY});

    ASSERT_TRUE(waitUntil(this->proxy_->invalidatingNotified));
    EXPECT_THAT(this->proxy_->changingNotifications.load(), Eq(0))
        << "Change of `changing` property on " << CODEGEN_INTERFACE_NAME << " shall not invoke handler for "
        << PROPERTY_CHANGES_INTERFACE_NAME;
}
