// The header is generated by sdbus-c++-xml2cpp from dbus-api/org.sdbuscpp.codegentests.xml
// during the build. This test fails to build if property change handlers are not generated
// for properties that emit PropertiesChanged signal, have unexpected signatures, or are
// generated for properties that never emit it.
#include "codegentests-proxy.h"

#include <cstdint>
#include <optional>
#include <string>
#include <type_traits>

namespace
{
    template <typename T, template <typename> class Op, typename = void>
    struct is_detected : std::false_type {};

    template <typename T, template <typename> class Op>
    struct is_detected<T, Op, std::void_t<Op<T>>> : std::true_type {};

    // `override` makes the build fail if a handler is missing or its signature differs
    class CodegenTestsProxy final : public org::sdbuscpp::codegentests_proxy
    {
    public:
        explicit CodegenTestsProxy(sdbus::IProxy& proxy) : codegentests_proxy(proxy) {}

    private:
        void onSetFilterAsyncReply(std::optional<sdbus::Error> /*error*/) override {}
        void onFilterModePropertyChanged(const std::optional<std::string>& /*value*/) override {}
    };

    class PropertyChangesProxy final : public org::sdbuscpp::codegentests::PropertyChanges_proxy
    {
    public:
        explicit PropertyChangesProxy(sdbus::IProxy& proxy) : PropertyChanges_proxy(proxy) {}

        // Declared in the derived class, so that protected handlers of the generated class are accessible
        template <typename T> using changing_handler_t = decltype(&T::onChangingPropertyChanged);
        template <typename T> using constant_handler_t = decltype(&T::onConstantPropertyChanged);
        template <typename T> using inheriting_handler_t = decltype(&T::onInheritingPropertyChanged);
        template <typename T> using write_only_handler_t = decltype(&T::onWriteOnlyPropertyChanged);

    private:
        void onChangingPropertyChanged(const std::optional<uint32_t>& /*value*/) override {}
        void onInvalidatingPropertyChanged(const std::optional<std::string>& /*value*/) override {}
        void onVariantPropertyChanged(const std::optional<sdbus::Variant>& /*value*/) override {}
    };

    // Sanity check of the detection itself: a generated handler must be detected
    static_assert( is_detected<PropertyChangesProxy, PropertyChangesProxy::changing_handler_t>::value
                 , "Handler of a property with EmitsChangedSignal=true is expected to be detected" );
    static_assert( !is_detected<PropertyChangesProxy, PropertyChangesProxy::constant_handler_t>::value
                 , "No change handler is expected for a property with EmitsChangedSignal=const" );
    static_assert( !is_detected<PropertyChangesProxy, PropertyChangesProxy::inheriting_handler_t>::value
                 , "No change handler is expected for a property inheriting interface-level EmitsChangedSignal=false" );
    static_assert( !is_detected<PropertyChangesProxy, PropertyChangesProxy::write_only_handler_t>::value
                 , "No change handler is expected for a write-only property" );
}
